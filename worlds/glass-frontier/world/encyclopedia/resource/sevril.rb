  prose <<~PROSE
    Lithren riggers call the translucent cords found in some old suspended works sevril. Fine ceramic fibers run through a flexible protective matrix, braided so that many strands share tension. A broad band can hold a startling weight while appearing little thicker than a folded garment. Its rating depends on its surviving section and condition; color alone cannot establish either.

    The fibers resist pulling along their length and suffer under sharp bends and abrasive contact. Old fittings use wide saddles and shallow curves. A cord that survives beneath a smooth saddle may fail when a buyer ties the recovered length into a tight knot. The spreading white brush at a damaged end consists of broken load-bearing strands.
