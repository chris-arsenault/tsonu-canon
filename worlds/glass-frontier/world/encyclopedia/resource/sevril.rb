  prose <<~PROSE, section: :trade, heading: "Lengths Worth Keeping"
    Long sound bands let expedition crews suspend platforms where heavy rigid beams would be difficult to carry. Modern covers protect exposed surfaces during reuse. Rigging crews inspect the saddles as closely as the cord: a nick hidden under a mounting can be the first part that fails under a new load.

    Detached stock is difficult to transport without creasing it. Buyers pay for lengths still wound around their broad original carriers, and for complete fittings that show how the makers spread the force. Short ends remain useful to investigators comparing the fibers and protective matrix. Modern imitations require thicker sections for the same tested load.

    The nearly transparent weave can conceal a structural connection from someone approaching under flat illumination. A lamp moved sideways picks out its strands. A person cutting what looks like a loose curtain tie can release the loaded work above it.
