    Issava stems turn slowly toward warm surfaces carrying animal oils. On contact, small pads swell along the inner curve and bring the thorns against their support. A heated scented rod can guide young growth into an arch. A bare wrist held still can receive the same treatment. Repeatedly tearing a stem away leaves wounds in both the plant and the handler.

    The gardeners aboard #{ref :olenvar} cultivate several lines, exchanging siblings with #{ref :seren} and #{ref :miraeth}. Broad-flowered plants make comfortable shaded screens when their gripping stems face away from a seat. Narrow-flowered lines grow denser thorns and are kept behind railings. Blooms from sibling cuttings can differ enough that recipients return to compare them at the vessel's next visit.

    Warmth and scent explain many ordinary movements. They have failed to reproduce all the garden's choices: some beds turn toward a distant visitor while a nearer scented rod remains ignored. Gardeners keep those observations with the particular bed. Issava grown elsewhere still grips, flowers and produces cuttings without demonstrating the same selectivity. Owners buy it for the blooms, for a living enclosure or because someone once gave them a piece of a plant they loved.
