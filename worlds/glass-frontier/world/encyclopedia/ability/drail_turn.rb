    Hab riggers use the same movement to approach a high work platform while carrying awkward tools. Their slow turns draw little applause but leave both hands free at the landing. A missed catch remains a fall, and a ribbon wrapped too tightly around the hip can make a dancer swing headfirst. Skilled performers make the release conspicuous when teaching and conceal it when entertaining an audience.
