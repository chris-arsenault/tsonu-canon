  prose <<~PROSE
    Drail ribbons hang as broad flat bands whose two edges feel different beneath the fingers. One has a raised braid; the other has paired soft ridges. A dancer turning around the band can recover its orientation without looking up. Short sleeves slide over the body of the ribbon, allowing a partner to control friction without trapping a hand in a knot.

    The #{ref :the_uncaught, "Uncaught"} teach with plain ribbons at #{ref :drail}. Performance bands carry color along one edge and invitations tied outside the gripping length. A decoration that crosses both edges can conceal a dangerous half-turn. Experienced dancers inspect a borrowed ribbon with their hands before climbing it, especially when a beautiful old band has been repaired in unfamiliar fiber.

    Musicians bring ribbons to rehearsal rooms at #{ref :fermata_station}, where they also carry lights and scenery. The same band makes a comfortable lifting sling when its whole width supports the load. Edge cuts, heated fibers and narrow knots greatly reduce its strength. A stage ribbon can still hang a painted screen after it has become unfit for a dancer, so its presence overhead alone says little about what it will carry.
  PROSE
